/**
 * Regenerates app/lib/access/legacy-nav.ts from the Sidebar.tsx NAV_BY_ROLE / MY_WORKSPACE
 * literals (COMPANY_OS_PLAN.md Phase 1). The file is DATA ONLY and a verbatim snapshot of
 * the sidebar so the registry can describe today's navigation without anyone retyping ~500
 * lines. `npm run check:parity` fails if the snapshot and Sidebar.tsx ever differ.
 *
 *   npx tsx scripts/gen-legacy-nav.ts
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { extractConst } from './lib/extract-literal';

const ROOT = path.resolve(__dirname, '..');
const SIDEBAR = path.join(ROOT, 'app', 'components', 'layout', 'Sidebar.tsx');
const OUT = path.join(ROOT, 'app', 'lib', 'access', 'legacy-nav.ts');

const navByRole = extractConst(SIDEBAR, 'NAV_BY_ROLE');
const myWorkspace = extractConst(SIDEBAR, 'MY_WORKSPACE');

interface Sec { title: string; items: { label: string; href: string; icon: string }[] }
function fmtSection(sec: Sec, indent: string): string {
    const items = sec.items.map((i) => `${indent}    ${JSON.stringify(i)},`).join('\n');
    return `${indent}{ title: ${JSON.stringify(sec.title)}, items: [\n${items}\n${indent}] }`;
}
function fmtRoles(map: Record<string, Sec[]>): string {
    return '{\n' + Object.entries(map).map(([role, secs]) =>
        `  ${JSON.stringify(role)}: [\n${secs.map((s) => fmtSection(s, '    ')).join(',\n')},\n  ],`).join('\n') + '\n}';
}

const header = `/**
 * GENERATED by scripts/gen-legacy-nav.ts from app/components/layout/Sidebar.tsx — do not edit by hand.
 * Verbatim snapshot of the sidebar's hardcoded navigation (icon = lucide component NAME).
 * Parity with Sidebar.tsx is enforced by \`npm run check:parity\`. Edge-safe: data only.
 * Replaced by registry-driven navigation in Phase 3 (docs/COMPANY_OS_PLAN.md §7.6).
 */
export interface LegacyNavItem { readonly label: string; readonly href: string; readonly icon: string }
export interface LegacyNavSection { readonly title: string; readonly items: readonly LegacyNavItem[] }

export const LEGACY_MY_WORKSPACE: LegacyNavSection = ${fmtSection(myWorkspace as Sec, '')};

export const LEGACY_NAV_BY_ROLE: Record<string, readonly LegacyNavSection[]> = ${fmtRoles(navByRole as Record<string, Sec[]>)};
`;
fs.writeFileSync(OUT, header);
console.log(`Wrote ${path.relative(ROOT, OUT)}`);
